let currentLang = detectLanguage()

export function getLanguage() {
  return currentLang
}

export function isSpanish() {
  return currentLang === 'es'
}

// Escolha manual (localStorage) > idioma do navegador (pt* -> pt, es* -> es,
// qualquer outro -> pt padrão).
export function detectLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'pt' || saved === 'es') return saved
  } catch {
    /* storage indisponível */
  }
  const nav = (navigator.language || navigator.userLanguage || '').toLowerCase()
  if (nav.startsWith('pt')) return 'pt'
  if (nav.startsWith('es')) return 'es'
  return 'pt'
}

export function setLanguage(lang) {
  currentLang = lang === 'es' ? 'es' : 'pt'
  try {
    localStorage.setItem(STORAGE_KEY, currentLang)
  } catch {
    /* storage indisponível */
  }
  window.dispatchEvent(new Event('pm:lang-changed'))
}

// t('chave', { var: valor }) — texto no idioma ativo, com interpolação {var}.
export function t(key, vars) {
  const dict = translations[currentLang] || translations.pt
  let s = dict[key]
  if (s === undefined) s = translations.pt[key]
  if (s === undefined) s = key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split('{' + k + '}').join(String(v))
    }
  }
  return s
}

// plural('songs', n) -> '1 música' / '3 músicas' (chaves .one/.other).
export function plural(key, n) {
  return t(key + (n === 1 ? '.one' : '.other'), { n })
}

// translateBackendError traduz mensagens conhecidas do backend (pt-BR) e
// erros por status HTTP para o idioma ativo. Retorna a mensagem original
// quando nada é reconhecido.
const backendErrorMap = {
  'Não autenticado': 'errors.notAuthenticated',
  'Sem permissão': 'errors.forbidden',
  'Não encontrado': 'errors.notFound',
  'Já existe um usuário com esse e-mail, usuário ou telefone': 'errors.duplicate',
  'Erro interno': 'errors.internal',
  'Arquivo de áudio inválido ou corrompido': 'errors.invalidAudio',
  'Arquivo de vídeo inválido ou corrompido': 'errors.invalidVideo',
  'Formato de áudio não suportado': 'errors.invalidAudio',
  'Formato de vídeo não suportado': 'errors.invalidVideo',
  'Arquivo muito grande': 'errors.tooLarge',
}

export function translateBackendError(msg, status) {
  if (msg) {
    const key = backendErrorMap[msg]
    if (key) return t(key)
  }
  if (status) {
    if (status === 401) return t('errors.notAuthenticated')
    if (status === 403) return t('errors.forbidden')
    if (status === 404) return t('errors.notFound')
    if (status === 409) return t('errors.duplicate')
    if (status === 400) return msg || t('errors.internal')
  }
  return msg || t('errors.internal')
}

// Selector de idioma compacto (login, sidebar e configurações).
export function languageSelector(extraClass = '') {
  const wrap = document.createElement('div')
  wrap.className = 'lang-selector' + (extraClass ? ' ' + extraClass : '')
  for (const [code, label] of [['pt', '🇧🇷 Português'], ['es', '🇪🇸 Español']]) {
    const btn = document.createElement('button')
    btn.type = 'button'
    btn.className = 'lang-btn' + (currentLang === code ? ' active' : '')
    btn.textContent = label
    btn.setAttribute('aria-pressed', String(currentLang === code))
    btn.addEventListener('click', () => {
      if (currentLang === code) return
      setLanguage(code)
    })
    wrap.appendChild(btn)
  }
  return wrap
}

